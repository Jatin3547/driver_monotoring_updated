@router.get("/video-feed")
def monitoring_video_feed():
    def frame_stream():
        while True:
            frame_bytes = get_video_frame()
            if frame_bytes:
                yield (
                    b"--frame\r\n"
                    b"Content-Type: image/jpeg\r\n\r\n" + frame_bytes + b"\r\n"
                )
            time.sleep(0.033)

    return StreamingResponse(
        frame_stream(),
        media_type="multipart/x-mixed-replace; boundary=frame",
        headers={
            "Access-Control-Allow-Origin": "*",
            "Cache-Control": "no-cache, no-store, must-revalidate",
            "Pragma": "no-cache",
            "Expires": "0",
        },
    )


@router.get("/current-snapshot")
def monitoring_current_snapshot():
    """Returns freshest live JPEG camera frame for incident evidence snapshots."""
    detector = get_detector()
    frame_bytes = None
    if detector and hasattr(detector, "get_latest_jpeg_frame"):
        frame_bytes = detector.get_latest_jpeg_frame()
    if not frame_bytes and detector and hasattr(detector, "camera"):
        ok, frame, _ = detector.camera.get_latest_frame()
        if ok and frame is not None:
            import cv2
            ret, buf = cv2.imencode(".jpg", frame, [int(cv2.IMWRITE_JPEG_QUALITY), 85])
            if ret:
                frame_bytes = buf.tobytes()

    if frame_bytes:
        return Response(
            content=frame_bytes,
            media_type="image/jpeg",
            headers={
                "Access-Control-Allow-Origin": "*",
                "Cache-Control": "no-cache, no-store, must-revalidate",
            },
        )
    raise HTTPException(status_code=404, detail="No active camera frame available")


@router.post("/release-camera")
def release_camera():
    """Explicitly releases any backend cv2 hardware capture lock so the browser can access it."""
    detector = get_detector()
    if detector and hasattr(detector, "camera") and hasattr(detector.camera, "release_hardware"):
        detector.camera.release_hardware()
        return {"ok": True, "message": "Camera hardware released successfully"}
    return {"ok": True, "message": "No active hardware lock to release"}


@router.get("/probe-network-camera")
def probe_network_camera(url: str = "http://192.168.0.4:4747/video"):
    """Quick probe to test if DroidCam Wi-Fi stream or IP camera is reachable on the local network."""
    import socket
    from urllib.parse import urlparse
    host = "192.168.0.4"
    port = 4747
    try:
        parsed = urlparse(url)
        host = parsed.hostname or "192.168.0.4"
        port = parsed.port or (4747 if "4747" in url else 80)
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            s.settimeout(1.5)
            s.connect((host, port))
            return {
                "reachable": True,
                "host": host,
                "port": port,
                "url": url,
                "message": f"DroidCam endpoint at {host}:{port} is reachable and responding."
            }
    except Exception as exc:
        return {
            "reachable": False,
            "host": host,
            "port": port,
            "url": url,
            "message": f"Could not connect to {url}: {exc}. Ensure DroidCam is running on your phone and connected to the same Wi-Fi."
        }


@router.post("/select-source")
async def select_camera_source(request: Request):
    """Allows dynamically switching camera source in the backend (e.g. DroidCam Wi-Fi vs Laptop/USB webcam)."""
    data = await request.json()
    source_type = data.get("sourceType") or data.get("source", "")
    url = data.get("url", "http://192.168.0.4:4747/video")

    detector = get_detector()
    if detector and hasattr(detector, "camera"):
        if source_type in ("webcam", "browser_usb"):
            detector.camera.release_hardware()
            return {"ok": True, "sourceType": "webcam", "activeSource": "browser_usb"}
        elif source_type in ("droidcam",) or "://" in str(source_type) or "://" in str(url):
            target_url = url if source_type == "droidcam" else str(source_type)
            detector.camera.switch_source(target_url)
            return {"ok": True, "sourceType": "droidcam", "activeSource": target_url}
        elif source_type:
            detector.camera.switch_source(source_type)
            return {"ok": True, "sourceType": "custom", "activeSource": str(source_type)}
    return {"ok": False, "error": "Detector not active"}


@router.post("/camera-frame")
async def push_camera_frame(request: Request):
    """Receives a JPEG camera frame uploaded directly from browser / USB bridge."""
    detector = get_detector()
    if detector is None or not hasattr(detector, "camera"):
        return {"ok": False, "error": "Live camera detector is not active"}

    body = await request.body()
    if not body:
        return {"ok": False, "error": "Empty body"}

    try:
        import cv2
        import numpy as np

        nparr = np.frombuffer(body, np.uint8)
        frame = cv2.imdecode(nparr, cv2.IMREAD_COLOR)
        if frame is None:
            return {"ok": False, "error": "Failed to decode frame"}

        detector.camera.inject_frame(frame, source_name="browser_usb")
        return {"ok": True, "source": "browser_usb"}
    except Exception as exc:
        return {"ok": False, "error": str(exc)}


@router.get("/events")
def monitoring_events(db: Session = Depends(get_db), limit: int = 25):
    from app.ai.factory import active_source

    detector = get_detector()
    if active_source() == "live":
        drivers = [d for d in db.query(Driver).all() if d.code == "DRV-001" and d.status in _ONLINE_STATUSES and d.assigned_vehicle_id]
    else:
        drivers = [d for d in db.query(Driver).all() if d.status in _ONLINE_STATUSES and d.assigned_vehicle_id][:3]

    for driver in drivers:
        recent = (
            db.query(SafetyEvent)
            .filter(SafetyEvent.driver_id == driver.id)
            .order_by(SafetyEvent.timestamp.desc())
            .first()
        )
        if recent:
            recent_ts = recent.timestamp if recent.timestamp.tzinfo else recent.timestamp.replace(tzinfo=timezone.utc)
            if (datetime.now(timezone.utc) - recent_ts).total_seconds() < 15:
                continue

        vehicle = db.query(Vehicle).filter(Vehicle.id == driver.assigned_vehicle_id).first()
        if not vehicle:
            continue

        try:
            detections = detector.analyze_frame(driver.code)
        except Exception:
            # Live camera unavailable etc. — skip silently rather than
            # fabricate a result. This is the honest failure path.
            continue

        for detection in detections:
            process_detection(db, driver, vehicle, detection)

    driver_map = {d.id: d.code for d in db.query(Driver).all()}
    vehicle_map = {v.id: v.code for v in db.query(Vehicle).all()}
    events = db.query(SafetyEvent).order_by(SafetyEvent.timestamp.desc()).limit(limit).all()
    return [
        safety_event_to_dict(e, driver_map.get(e.driver_id, e.driver_id), vehicle_map.get(e.vehicle_id, e.vehicle_id))
        for e in events
    ]
