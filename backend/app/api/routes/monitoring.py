"""Live AI Monitoring endpoints.

/status     -> per-driver signal snapshot (simulation-generated by default;
               see README AI section for AI_MODE=live).
/events     -> real reads from the safety_events table. Also triggers a
               fresh detection pass for a couple of online drivers on each
               call (rate-limited), routed through app.services.safety_engine
               so incident/alert escalation is identical whether triggered
               by REST polling or by the WebSocket background loop in
               main.py.
/ai-status  -> what's actually active right now (demo vs live, camera
               index, whether optional CV deps are installed) — never
               claims "live" unless a live detector genuinely started.
"""

from datetime import datetime, timezone
import time
from fastapi import APIRouter, Depends, HTTPException, Request, Response
from fastapi.responses import StreamingResponse
from sqlalchemy.orm import Session

from app.ai.factory import ai_status, get_detector, get_driver_status, get_video_frame
from app.api.deps import get_db
from app.models import Driver, SafetyEvent, Vehicle
from app.services.safety_engine import process_detection
from app.services.serializers import safety_event_to_dict

router = APIRouter()

_ONLINE_STATUSES = {"active", "on-trip"}


@router.get("/status")
def monitoring_status(db: Session = Depends(get_db)):
    drivers = [d for d in db.query(Driver).all() if d.status in _ONLINE_STATUSES and d.assigned_vehicle_id]
    results = []
    for driver in drivers:
        vehicle = db.query(Vehicle).filter(Vehicle.id == driver.assigned_vehicle_id).first()
        status = get_driver_status(driver.code, vehicle.code)
        results.append(status)
    return results


