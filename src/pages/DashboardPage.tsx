import { useAsyncData } from '@/hooks/useAsyncData';
import { getDrivers } from '@/services/api/driverService';
import { getVehicles } from '@/services/api/vehicleService';
import { getIncidents, getAlerts } from '@/services/api/incidentService';
import { getVehicleLocations } from '@/services/api/gpsService';
import { getSafetyTrend } from '@/services/api/analyticsService';
import { useFleetSocketEvent } from '@/hooks/useFleetSocketEvent';
import { FleetOverviewCards } from '@/components/dashboard/FleetOverviewCards';
import { AlertsFeed } from '@/components/dashboard/AlertsFeed';
import { FleetActivityChart } from '@/components/dashboard/FleetActivityChart';
import { FleetMap } from '@/components/map/FleetMap';
import { LoadingState, ErrorState } from '@/components/ui/States';
import { Card, CardHeader } from '@/components/ui/Card';
import { USE_MOCK_DATA } from '@/services/config';

export default function DashboardPage() {
  const { data: drivers, status: driversStatus, error: driversError, refetch: refetchDrivers } = useAsyncData(() => getDrivers(), []);
  const { data: vehicles, status: vehiclesStatus } = useAsyncData(() => getVehicles(), []);
  const { data: incidents, refetch: refetchIncidents } = useAsyncData(() => getIncidents(), []);
  const { data: alerts, refetch: refetchAlerts } = useAsyncData(() => getAlerts(), []);
  const { data: locations } = useAsyncData(() => getVehicleLocations(), []);
  const { data: trend } = useAsyncData(() => getSafetyTrend(), []);

  // Real-time: when a new incident/alert is generated by the backend's
  // AI escalation pipeline, refresh the affected panels so the dashboard
  // updates without a manual page reload. (GPS updates are intentionally
  // NOT wired here — the GPS Tracking page patches markers in place per
  // event; refetching the whole list on every one of the ~8 per-vehicle
  // gps_update messages every 5s would be a request storm for no benefit
  // on this summary map.)
  useFleetSocketEvent('incident_created', () => {
    refetchIncidents();
  });
  useFleetSocketEvent('alert_created', () => {
    refetchAlerts();
  });

  const loading = driversStatus === 'loading' || vehiclesStatus === 'loading';

  if (loading) return <LoadingState label="Loading fleet overview…" />;
  if (driversStatus === 'error') return <ErrorState message={driversError ?? 'Unknown error'} onRetry={refetchDrivers} />;
  if (!drivers || !vehicles || !incidents || !alerts || !locations || !trend) return null;

  return (
    <div className="space-y-6">
      <FleetOverviewCards drivers={drivers} vehicles={vehicles} incidents={incidents} />

      <div className="grid grid-cols-1 xl:grid-cols-3 gap-6">
        <div className="xl:col-span-2">
          <FleetActivityChart data={trend} />
        </div>
        <AlertsFeed alerts={alerts} />
      </div>

      <Card>
        <CardHeader
          title="Live fleet map"
          subtitle={USE_MOCK_DATA ? 'Simulated vehicle positions (demo mode)' : 'Simulated vehicle positions, updating live'}
        />
        <FleetMap locations={locations} vehicles={vehicles} drivers={drivers} />
      </Card>
    </div>
  );
}
